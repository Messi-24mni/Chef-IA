export function extractIngredientFocus(rawTitle: string, ing: Array<{ item: string }>): string {
  const lowerTitle = rawTitle.toLowerCase();
  for (const prefix of KNOWN_PREFIXES) {
    if (lowerTitle.startsWith(prefix.toLowerCase())) {
      return rawTitle.slice(prefix.length).trim();
    }
  }
  const fallbackMatch = rawTitle.match(/\bde\s+(.+)$/i);
  if (fallbackMatch?.[1]) {
    return fallbackMatch[1].trim();
  }
  return ing[1]?.item.toLowerCase() ?? ing[0]?.item.toLowerCase() ?? "tus ingredientes";
}

export function getOriginalDishTitle(r: RawInternationalInput): string {
  const focus = extractIngredientFocus(r.t, r.ing);
  const variantIdx = (r.n - 1) % 10;
  const countryMap = ORIGINAL_COUNTRY_NAMES[r.c];
  const familyList = countryMap?.[r.f];
  const baseOriginalName = familyList?.[variantIdx];

  if (!baseOriginalName) {
    return r.t;
  }

  return `${baseOriginalName} de ${focus}`;
}
